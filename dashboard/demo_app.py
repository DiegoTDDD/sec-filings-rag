"""Public demo of the SEC Filings RAG system (precomputed answers).

The full system needs local services (Qdrant + Ollama) that a free cloud host
can't run. This demo therefore serves answers that were generated ahead of time
by the real pipeline (see src/retrieval/precompute_demo.py) and saved to
demo_data.json. The answers and their cited sources are genuine outputs of the
RAG — this app just displays them, so it can run anywhere with zero backend.

For the live, interactive system (ask any question), see the main dashboard in
the repository README.

Run:
    streamlit run dashboard/demo_app.py
"""
import json
from pathlib import Path

import streamlit as st

DEMO_PATH = Path(__file__).resolve().parent / "demo_data.json"

st.set_page_config(page_title="SEC Filings RAG — Demo", page_icon="📄", layout="centered")


@st.cache_data
def load_demo():
    return json.loads(DEMO_PATH.read_text(encoding="utf-8"))


data = load_demo()

st.title("SEC Filings RAG — Demo")
st.caption(
    "Ask-anything RAG over the 10-K/10-Q filings of Apple, NVIDIA and JPMorgan, "
    "with answers grounded in the filings and cited to the exact sections."
)

st.info(
    "This is a **static demo** with precomputed answers, so it can run on a free "
    "host. The answers below were generated by the real pipeline (Qdrant + local "
    "embeddings + cross-encoder re-ranking + llama3.2). The fully interactive "
    "version runs locally — see the repository README.",
    icon="ℹ️",
)

# Map a display label to each precomputed question.
labels = []
for item in data:
    scope = item["ticker"] if item["ticker"] else "All companies"
    labels.append(f"[{scope}] {item['question']}")

choice = st.selectbox("Pick a question", labels)
selected = data[labels.index(choice)]

st.subheader("Answer")
st.write(selected["answer"])

st.subheader("Sources")
for i, s in enumerate(selected["sources"], 1):
    st.markdown(
        f"**[{i}]** {s['ticker']} · {s['form']} · filed {s['filing_date']} · "
        f"*{s['section'].replace('_', ' ')}*"
    )

st.divider()
st.caption(
    "Built by Diego Leonardo Alves de Andrade · "
    "[github.com/DiegoTDDD/sec-filings-rag](https://github.com/DiegoTDDD/sec-filings-rag)"
)
